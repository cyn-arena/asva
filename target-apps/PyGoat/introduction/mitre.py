_ALLOWED_BIN_OPS = {
    ast.Add: operator.add,
    ast.Sub: operator.sub,
    ast.Mult: operator.mul,
    ast.Div: operator.truediv,
    ast.FloorDiv: operator.floordiv,
    ast.Mod: operator.mod,
    ast.Pow: operator.pow,
}

_ALLOWED_UNARY_OPS = {
    ast.UAdd: operator.pos,
    ast.USub: operator.neg,
}


def _safe_eval_expression(expression):
    if not isinstance(expression, str) or len(expression) > 1000:
        raise ValueError("Invalid expression")

    try:
        node = ast.parse(expression, mode="eval").body
    except SyntaxError as exc:
        raise ValueError("Invalid expression") from exc

    def _eval(current_node):
        if isinstance(current_node, ast.Constant):
            if isinstance(current_node.value, (int, float, bool, str, type(None))):
                return current_node.value
            raise ValueError("Unsupported expression")

        if isinstance(current_node, ast.BinOp):
            op_type = type(current_node.op)
            if op_type not in _ALLOWED_BIN_OPS:
                raise ValueError("Unsupported expression")
            left = _eval(current_node.left)
            right = _eval(current_node.right)
            if op_type is ast.Pow and isinstance(right, (int, float)) and abs(right) > 1000:
                raise ValueError("Exponent too large")
            return _ALLOWED_BIN_OPS[op_type](left, right)

        if isinstance(current_node, ast.UnaryOp):
            op_type = type(current_node.op)
            if op_type not in _ALLOWED_UNARY_OPS:
                raise ValueError("Unsupported expression")
            return _ALLOWED_UNARY_OPS[op_type](_eval(current_node.operand))

        raise ValueError("Unsupported expression")

    return _eval(node)


def _is_safe_nmap_target(target):
    if not target or len(target) > 253:
        return False

    try:
        ipaddress.ip_address(target)
        return True
    except ValueError:
        pass

    try:
        ipaddress.ip_network(target, strict=False)
        return True
    except ValueError:
        pass

    hostname = target[:-1] if target.endswith(".") else target
    labels = hostname.split(".")
    if not labels or any(not label for label in labels):
        return False

    label_pattern = re.compile(r"^[A-Za-z0-9](?:[A-Za-z0-9-]{0,61}[A-Za-z0-9])?$")
    return all(label_pattern.match(label) for label in labels)


