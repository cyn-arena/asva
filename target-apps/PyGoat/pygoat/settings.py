def _read_secret_key(path):
    try:
        with open(path, 'r') as f:
            return f.read().strip()
    except OSError:
        return None


def _get_secret_key():
    for env_name in ('DJANGO_SECRET_KEY', 'SECRET_KEY'):
        secret_key = os.environ.get(env_name)
        if secret_key:
            return secret_key

    configured_file = os.environ.get('DJANGO_SECRET_KEY_FILE')
    if configured_file:
        secret_files = [configured_file]
    else:
        secret_files = [
            os.path.join(tempfile.gettempdir(), 'pygoat_secret_key'),
            os.path.join(BASE_DIR, '.secret_key'),
        ]

    for secret_file in secret_files:
        stored_key = _read_secret_key(secret_file)
        if stored_key:
            return stored_key

        generated_key = secrets.token_urlsafe(64)
        secret_dir = os.path.dirname(secret_file) or '.'
        try:
            os.makedirs(secret_dir, exist_ok=True)
            tmp_fd, tmp_path = tempfile.mkstemp(
                dir=secret_dir, prefix='.pygoat_secret_', text=True
            )
        except OSError:
            continue

        try:
            with os.fdopen(tmp_fd, 'w') as f:
                f.write(generated_key)
                f.flush()
                os.fsync(f.fileno())
            try:
                os.link(tmp_path, secret_file)
                return generated_key
            except FileExistsError:
                stored_key = _read_secret_key(secret_file)
                if stored_key:
                    return stored_key
                for _ in range(100):
                    time.sleep(0.01)
                    stored_key = _read_secret_key(secret_file)
                    if stored_key:
                        return stored_key
            except OSError:
                pass
        finally:
            try:
                os.unlink(tmp_path)
            except OSError:
                pass

    return secrets.token_urlsafe(64)


SECRET_KEY = _get_secret_key()

